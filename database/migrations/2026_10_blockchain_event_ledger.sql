-- Idempotent event ledger for the local/testnet chain bridge.
-- Amounts remain exact in base units; no floating-point conversion is performed.
CREATE TABLE IF NOT EXISTS blockchain_sync_state (
    chain_id bigint NOT NULL,
    contract_address text NOT NULL CHECK (contract_address ~ '^0x[0-9a-fA-F]{40}$'),
    last_synced_block bigint NOT NULL CHECK (last_synced_block >= 0),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (chain_id, contract_address)
);

CREATE TABLE IF NOT EXISTS blockchain_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chain_id bigint NOT NULL,
    contract_address text NOT NULL CHECK (contract_address ~ '^0x[0-9a-fA-F]{40}$'),
    transaction_hash text NOT NULL CHECK (transaction_hash ~ '^0x[0-9a-fA-F]{64}$'),
    log_index integer NOT NULL CHECK (log_index >= 0),
    block_number bigint NOT NULL CHECK (block_number >= 0),
    block_hash text NOT NULL CHECK (block_hash ~ '^0x[0-9a-fA-F]{64}$'),
    response_id bigint REFERENCES responses(id) ON DELETE RESTRICT,
    response_code text NOT NULL CHECK (response_code ~ '^[A-Z0-9-]{3,40}$'),
    event_type text NOT NULL CHECK (event_type IN ('donation','payout')),
    actor_address text NOT NULL CHECK (actor_address ~ '^0x[0-9a-fA-F]{40}$'),
    recipient_address text CHECK (recipient_address IS NULL OR recipient_address ~ '^0x[0-9a-fA-F]{40}$'),
    amount_raw numeric(78,0) NOT NULL CHECK (amount_raw > 0),
    asset_address text NOT NULL CHECK (asset_address ~ '^0x[0-9a-fA-F]{40}$'),
    asset_decimals smallint NOT NULL CHECK (asset_decimals BETWEEN 0 AND 36),
    purpose text,
    evidence_hash text,
    confirmation_status text NOT NULL CHECK (confirmation_status IN ('confirmed','unmatched')),
    observed_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (chain_id, contract_address, transaction_hash, log_index)
);
CREATE INDEX IF NOT EXISTS blockchain_events_response_idx
    ON blockchain_events(response_id, block_number DESC);
CREATE INDEX IF NOT EXISTS blockchain_events_status_idx
    ON blockchain_events(confirmation_status, observed_at DESC);

GRANT SELECT, INSERT, UPDATE, DELETE ON blockchain_sync_state, blockchain_events TO relieftrail_app;
GRANT USAGE, SELECT ON SEQUENCE blockchain_events_id_seq TO relieftrail_app;
